-- Qisma: move money between buckets.
-- A transfer is two linked ledger entries of kind 'transfer': minus on the source bucket,
-- plus on the destination. They are written together by one function, so the total across
-- all buckets never changes. Entries stay immutable.

-- Both legs of a transfer share one transfer_id (it is also the id of the source leg).
alter table public.entries
  add column transfer_id uuid,
  add constraint entries_transfer_id_is_transfer check (transfer_id is null or kind = 'transfer');
create index entries_transfer_id on public.entries (transfer_id) where transfer_id is not null;

-- Direct inserts are now limited to plain spend and adjustment entries.
-- Transfers (like allocations, invest/return and subscription payments) only come from a function,
-- because a single transfer entry on its own would make money appear or disappear.
drop policy entries_insert_own on public.entries;
create policy entries_insert_own on public.entries for insert to authenticated
  with check (
    (select auth.uid()) = user_id
    and kind in ('spend', 'adjustment')
    and investment_id is null
    and subscription_id is null
    and transfer_id is null
  );

-- Moves p_amount from one bucket to another, atomically.
-- p_id is generated by the app: a repeated submit fails on the primary key.
-- Refuses an amount larger than the source bucket's balance (QT001) and changes nothing.
-- If the two buckets live in different accounts the user still has to make the bank transfer:
-- the destination leg is left with transfer_done = false so it shows in the pending checklist.
create function public.transfer_between_buckets(
  p_id          uuid,
  p_from_bucket uuid,
  p_to_bucket   uuid,
  p_amount      bigint,
  p_on          date,
  p_note        text
) returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user         uuid := auth.uid();
  v_from_account uuid;
  v_to_account   uuid;
  v_balance      bigint;
  v_note         text := nullif(btrim(p_note), '');
begin
  if v_user is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  if p_id is null or p_from_bucket is null or p_to_bucket is null or p_on is null
     or p_amount is null or p_amount <= 0 then
    raise exception 'id, two buckets, a positive amount and a date are required' using errcode = '22023';
  end if;
  if p_from_bucket = p_to_bucket then
    raise exception 'source and destination must be different buckets' using errcode = '22023';
  end if;

  -- Lock both buckets, always in the same order, so two transfers cannot both spend one balance.
  perform 1 from public.buckets b
  where b.user_id = v_user and b.id in (p_from_bucket, p_to_bucket)
  order by b.id
  for update;

  select b.account_id into v_from_account from public.buckets b where b.id = p_from_bucket and b.user_id = v_user;
  if not found then
    raise exception 'source bucket not found' using errcode = 'P0002';
  end if;
  select b.account_id into v_to_account from public.buckets b where b.id = p_to_bucket and b.user_id = v_user;
  if not found then
    raise exception 'destination bucket not found' using errcode = 'P0002';
  end if;

  select coalesce(sum(e.amount), 0) into v_balance from public.entries e where e.bucket_id = p_from_bucket;
  if p_amount > v_balance then
    raise exception 'amount % is larger than the source balance %', p_amount, v_balance using errcode = 'QT001';
  end if;

  -- Source leg: money leaves. Nothing for the user to tick on this side.
  insert into public.entries (id, user_id, bucket_id, kind, amount, note, occurred_on, transfer_id, transfer_done)
  values (p_id, v_user, p_from_bucket, 'transfer', -p_amount, v_note, p_on, p_id, true);

  -- Destination leg: money arrives. Pending until the bank transfer is made, if one is needed.
  insert into public.entries (user_id, bucket_id, kind, amount, note, occurred_on, transfer_id, transfer_done)
  values (v_user, p_to_bucket, 'transfer', p_amount, v_note, p_on, p_id, v_from_account = v_to_account);

  return p_id;
end;
$$;

revoke all on function public.transfer_between_buckets(uuid, uuid, uuid, bigint, date, text) from public, anon;
grant execute on function public.transfer_between_buckets(uuid, uuid, uuid, bigint, date, text) to authenticated;
